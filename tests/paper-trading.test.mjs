import assert from 'node:assert/strict';
import test from 'node:test';
import {subscribeCaptainChanges} from '../src/api/captain-stream.ts';
import {parseExecutionProgress,parseTradingReturns} from '../src/api/generated/paper-trading-contracts.ts';
import {orderProgressMessage} from '../src/api/order-progress.ts';
const at='2026-10-11T00:00:00Z';
const progress={stage:'WAITING_VALUATION',eligibleAt:at,expiresAt:at,lastAttemptedAt:null,attempts:0,observationSourceAt:null,observationAgeMs:null,reason:'holdings_unpriced',retryAfterMs:2000};
test('execution progress preserves missing price evidence and explains vault valuation',()=>{
 assert.equal(parseExecutionProgress(progress).observationAgeMs,null);assert.match(orderProgressMessage(progress),/vault holdings/);
 assert.throws(()=>parseExecutionProgress({...progress,attempts:-1}));assert.throws(()=>parseExecutionProgress({...progress,stage:'DONE'}));
});
test('net trading returns validate gaps and chronological records',()=>{
 const result={mode:'PAPER',range:'ALL',method:'CHAINED_ECONOMIC_UNIT_PRICE',intervalSeconds:86400,baselineAt:at,asOf:at,coverage:'PARTIAL',netReturnPercent:null,points:[{at,indexValue:null,hasGap:true}],methodology:'Deposits excluded'};
 assert.equal(parseTradingReturns(result).points[0].indexValue,null);
 assert.throws(()=>parseTradingReturns({...result,points:[...result.points,...result.points]}));
 assert.throws(()=>parseTradingReturns({...result,netReturnPercent:'NaN'}));
});
test('Captain stream authenticates, deduplicates revisions, resyncs and disposes account state',async()=>{
 const frames=[],revisions=[],connections=[];
 const ws={readyState:1,send:v=>frames.push(JSON.parse(v)),close(){this.closed=true;}};
 const stop=subscribeCaptainChanges({origin:'https://example.com',getAccessToken:async()=> 'secret',onRevision:r=>revisions.push(r),onConnection:r=>connections.push(r),socketFactory:url=>{assert.equal(url,'wss://example.com/v0/ws');return ws;}});
 ws.onopen();await Promise.resolve();assert.deepEqual(frames[0],{type:'authenticate',accessToken:'secret'});
 const emit=v=>ws.onmessage?.({data:JSON.stringify(v)});
 emit({type:'authenticated'});assert.deepEqual(frames[1],{type:'subscribe',channel:'captain.dashboard'});
 for(const [type,revision] of [['resync_required','4'],['captain.updated','4'],['captain.updated','3'],['captain.updated','5'],['resync_required','5']])emit({type,revision,channel:'captain.dashboard'});
 assert.deepEqual(revisions,['4','5','5']);stop();emit({type:'captain.updated',revision:'6',channel:'captain.dashboard'});assert.equal(revisions.length,3);assert.equal(ws.closed,true);assert.equal(connections.at(-1),false);
});
test('an auth request resolving after account cleanup never sends credentials',async()=>{
 let release;const sent=[];const ws={readyState:1,send:v=>sent.push(v),close(){}};
 const stop=subscribeCaptainChanges({origin:'http://example.com',getAccessToken:()=>new Promise(r=>{release=r;}),onRevision(){},onConnection(){},socketFactory:()=>ws});
 ws.onopen();stop();release('old-account');await Promise.resolve();assert.deepEqual(sent,[]);
});

